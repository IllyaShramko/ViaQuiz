function getNestedValue(obj: NestedRecord, path: string): string {
  const result = path.split('.').reduce<string | NestedRecord | undefined>(
    (acc, key) => {
      if (acc === undefined || typeof acc === 'string') return undefined;
      return acc[key];
    },
    obj,
  );
  return typeof result === 'string' ? result : path;
}

let currentLocale: Locale = (localStorage.getItem('viaquiz-locale') as Locale) || 'uk';
const listeners: Set<() => void> = new Set();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  localStorage.setItem('viaquiz-locale', locale);
  listeners.forEach(fn => fn());
}

export function t(key: string): string {
  return getNestedValue(translations[currentLocale], key);
}

export function pluralize(count: number, words: { uk: [string, string, string], en: [string, string] }): string {
  if (currentLocale === 'en') {
    return count === 1 ? words.en[0] : words.en[1];
  }
  // uk rules
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) return words.uk[0];
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return words.uk[1];
  return words.uk[2];
}

export function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}
